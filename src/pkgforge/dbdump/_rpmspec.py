_SYSUSERS_TAG = "PKGFORGE_SYSUSERS"


def _percent(text: str) -> str:
    """``text`` with ``%`` doubled: rpm expands macros in every line of a spec."""
    return text.replace("%", "%%")


def _tag(name: str, value: str) -> str:
    return f"{name + ':':<16}{_percent(value)}\n"


def _description(
    fmt: str, where: str, text: typing.Optional[str], fallback: str
) -> str:
    """The ``%description`` body: ``text``, else the summary ``fallback``.

    rpm expands a line before it looks for a section or a conditional, so a
    line whose first non-blank character is ``%`` would start one even with
    its ``%`` doubled, and it drops a line starting with ``#`` as a comment:
    both are refused, naming ``where`` (the table)."""
    key, body = ("description", text) if text else ("summary", fallback)
    for number, line in enumerate(body.split("\n"), 1):
        first = line.lstrip(" ")[:1]
        if first in ("%", "#"):
            raise UsageError(
                f"{fmt}: {where} {key} line {number} starts with {first!r}, "
                "which rpm reads as spec syntax: reword that line"
            )
    return _percent(body).rstrip("\n") + "\n"


def _unit_scriptlets(units: typing.Sequence[str]) -> typing.Tuple[str, str, str]:
    """The ``%post``, ``%preun`` and ``%postun`` lines for ``units``, each
    guarded so it expands to nothing where rpm has no systemd macros."""
    names = _percent(" ".join(units))
    return (
        f"%{{?systemd_post:%systemd_post {names}}}\n",
        f"%{{?systemd_preun:%systemd_preun {names}}}\n",
        f"%{{?systemd_postun_with_restart:%systemd_postun_with_restart {names}}}\n",
    )


def _spec(
    config: ProjectConfig,
    entries: FileEntries,
    *,
    fmt: str,
    sysusers_pre: bool,
    install: typing.Sequence[str],
    guard: bool,
) -> str:
    """The spec text for ``config`` and ``entries``.

    ``fmt`` names the caller in errors and marker comments, ``install`` is the
    body of ``%install`` (lines ending in a newline), ``sysusers_pre`` adds the
    ``%pre`` that creates the accounts (rpm below 4.19), and ``guard`` adds the
    check that the build was given ``--define "pkgforge_config PATH"``.

    Raises :class:`~pkgforge.exceptions.UsageError` for a missing ``[package]``
    key, an ``any`` subpackage of an ``all`` main package and a description
    line rpm would read as spec syntax.
    """
    main = config.package
    _require_keys(fmt, config, ("version", "summary", "license"), ("summary",))
    assert main is not None  # _require_keys: name is required
    groups = _packages(entries, config)
    paths = {name: {path for path, _entry in group} for name, group in groups}
    main_arch = main.arch or "any"
    for sub in config.packages:
        if (sub.arch or main_arch) == "any" and main_arch == "all":
            raise UsageError(
                f"{fmt}: [[packages]] {sub.name} is arch any, but "
                f"{main.name} is arch all"
            )

    lines: typing.List[str] = []
    if guard:
        lines += [
            f"# Generated by pkgforge dbdump -f {fmt} from pkgforge.cfg.\n",
            "# An existing spec is kept: regenerate it with --force.\n",
            "# Build: rpmbuild -bb --define "
            f'"pkgforge_config PATH" {main.name}.spec, PATH being pkgforge.cfg.\n',
            "%{!?pkgforge_config:%{error:define pkgforge_config as the path of "
            f'pkgforge.cfg: rpmbuild -bb --define "pkgforge_config PATH" {main.name}.spec'
            "}}\n",
        ]
    else:
        lines.append(f"# Generated by pkgforge {fmt}.\n")
    lines += [
        "\n",
        "# The package holds the recorded files unchanged.\n",
        "%global __os_install_post %{nil}\n",
        "%global debug_package %{nil}\n",
        "\n",
        _tag("Name", main.name),
        _tag("Version", main.version or ""),
        _tag("Release", main.release or "1"),
        _tag("Summary", main.summary or ""),
        _tag("License", main.license or ""),
    ]
    if main.homepage:
        lines.append(_tag("URL", main.homepage))
    if main_arch == "all":
        lines.append(_tag("BuildArch", "noarch"))
    lines.extend(_tag("Requires", item) for item in main.rpm.requires)
    lines.append("\n%description\n")
    lines.append(_description(fmt, "[package]", main.description, main.summary or ""))
    for sub in config.packages:
        lines.append(f"\n%package -n {sub.name}\n")
        lines.append(_tag("Summary", sub.summary or ""))
        if (sub.arch or main_arch) == "all" and main_arch != "all":
            lines.append(_tag("BuildArch", "noarch"))
        lines.extend(_tag("Requires", item) for item in sub.rpm.requires)
        lines.append(f"\n%description -n {sub.name}\n")
        lines.append(
            _description(
                fmt, f"[[packages]] {sub.name}", sub.description, sub.summary or ""
            )
        )

    lines.append("\n%install\n")
    lines.extend(install)

    sysusers = sysusers_text(config) if sysusers_pre else ""
    sysusers_file = f"{SYSUSERS_DIR}/{main.name}.conf"
    tmpfiles_file = f"{TMPFILES_DIR}/{main.name}.conf"
    for name, group in groups:
        section = "" if name == main.name else f" -n {name}"
        units = unit_names(group)
        if sysusers and sysusers_file in paths[name]:
            lines.append(f"\n%pre{section}\n")
            lines.append(f"systemd-sysusers - <<'{_SYSUSERS_TAG}' || :\n")
            lines.append(_percent(sysusers))
            lines.append(f"{_SYSUSERS_TAG}\n")
        post, preun, postun = _unit_scriptlets(units) if units else ("", "", "")
        if tmpfiles_file in paths[name]:
            post += f"systemd-tmpfiles --create {tmpfiles_file} >/dev/null 2>&1 || :\n"
        # An rpm package takes one scriptlet of each kind, so the unit and
        # tmpfiles lines share a %post.
        for tag, body in (("post", post), ("preun", preun), ("postun", postun)):
            if body:
                lines.append(f"\n%{tag}{section}\n{body}")
    for name, _group in groups:
        section = "" if name == main.name else f" -n {name}"
        lines.append(
            f"\n%files{section} -f %{{_builddir}}/pkgforge-files/files-{name}.txt\n"
        )
    return "".join(lines)


class RPMSpec(DumpFormat):
    """The RPM spec for the packages ``pkgforge.cfg`` declares: one ``Name``
    preamble (``[package]``), a ``%package -n`` block per ``[[packages]]``
    element, a ``%install`` that runs ``pkgforge stage --init`` and writes one
    ``%files`` list per package, and one ``%files -f`` per package. A
    ``%post`` creates the ``tmpfiles.d`` paths of the package that ships
    ``/usr/lib/tmpfiles.d/NAME.conf``.

    A package that records a systemd unit directly in
    ``/usr/lib/systemd/system`` gets ``%systemd_post``, ``%systemd_preun`` and
    ``%systemd_postun_with_restart`` for its units. They need
    systemd-rpm-macros (or EL8's systemd) when the package is built, and
    expand to nothing without them.

    Needs ``[package]`` ``name``, ``version``, ``summary`` and ``license``, and a
    ``summary`` for each ``[[packages]]`` element; an ``any`` subpackage of an
    ``all`` main package is refused. Every configuration text has its ``%``
    doubled, so no macro is read from the file, and a ``%description`` line
    whose first non-blank character is ``%`` or ``#`` is refused, since rpm
    reads it as a section, a conditional or a comment. The spec holds no absolute
    path: build it with ``rpmbuild -bb --define "pkgforge_config PATH"
    NAME.spec``, ``PATH`` being ``pkgforge.cfg``, and ``pkgforge`` on ``PATH``.

    The package is built from the recorded files unchanged (no brp scripts, no
    debuginfo). Writes a file or ``-``; a spec that exists is kept with a
    warning unless ``force``, since it is meant to be edited. rpm 4.19+
    creates the accounts from the shipped ``sysusers.d`` file; use
    :class:`RPMSpecPre419` for older rpm.
    """

    NAME = "rpmspec"
    KEEP_EXISTING = True
    #: The ``dbdump -f`` format that writes the per-package ``%files`` lists.
    _LISTS = "rpmspecfiles"
    #: Whether ``%pre`` creates the accounts (rpm below 4.19 does not read the
    #: shipped ``sysusers.d`` file).
    _SYSUSERS_PRE = False

    def render(self, entries: FileEntries, context: DumpContext) -> bytes:
        install = [
            "export PKGFORGE_ROOT=%{buildroot} PKGFORGE_DB=%{_builddir}/pkgforge.jsonl\n",
            'pkgforge -q --config "%{pkgforge_config}" stage --init\n'
            "mkdir -p %{_builddir}/pkgforge-files\n"
            f'pkgforge -q --config "%{{pkgforge_config}}" dbdump -f {self._LISTS} '
            "%{_builddir}/pkgforge-files\n",
        ]
        spec = _spec(
            context.config,
            entries,
            fmt=self.NAME,
            sysusers_pre=self._SYSUSERS_PRE,
            install=install,
            guard=True,
        )
        return spec.encode("utf-8")

    def check_output(self, output: Path) -> None:
        if output.is_dir():
            raise UnsupportedOutputError(
                f"{self.NAME} writes one spec file; OUTPUT must be a file or "
                f"'-', got directory {output}"
            )

    def write(
        self, rendered: Rendered, output: Path, *, force: bool = False
    ) -> typing.List[Path]:
        files = _keep_existing({output: typing.cast(bytes, rendered)}, force)
        _write_files(files)
        return list(files)


class RPMSpecPre419(RPMSpec):
    """:class:`RPMSpec` for rpm older than 4.19: the ``%files`` lists are
    ``rpmspecfiles-pre419``'s, and a ``%pre`` of the package that ships the
    ``sysusers.d`` file creates the accounts itself."""

    NAME = "rpmspec-pre419"
    _LISTS = "rpmspecfiles-pre419"
    _SYSUSERS_PRE = True
