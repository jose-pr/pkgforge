#: Characters dh_install/dh_installdirs read as glob syntax in a SOURCE line,
#: plus the escaping backslash; escaping ``{`` also makes a literal ``${`` read
#: as literal (``$\{``), so a SOURCE needs no ``$`` handling.
_DH_GLOB_CHARS = "\\*?[]{}"
_DH_SRC_TABLE = str.maketrans(
    {**{c: "\\" + c for c in _DH_GLOB_CHARS}, " ": "${Space}"}
)


def _dh_src(rel: str) -> str:
    """Escape a debian ``install``/``dirs`` SOURCE (debhelper compat 13+).

    Backslash-escapes every glob character so the name matches only
    itself, and ``${Space}``-escapes a literal space; a leading ``#`` (the
    line's own first character) is backslash-escaped too, since dh_install
    treats a line starting with ``#`` as a comment. A bare ``$`` is left
    alone -- see :func:`_dh_dest`.
    """
    text = rel.translate(_DH_SRC_TABLE)
    if text.startswith("#"):
        text = "\\" + text
    return text


def _dh_dest(rel: str) -> str:
    """Escape a debian ``install``/``dirs`` DESTINATION.

    dh_install never globs the destination (a backslash there is kept
    literally), so only a literal ``${`` (an unresolved compat-13 variable)
    and a space need handling; a bare ``$`` not followed by ``{`` stays
    literal, which also works on compat 12.
    """
    return rel.replace("${", "${Dollar}{").replace(" ", "${Space}")


#: The ``fixperms`` header (the whole file with no pin). An empty ``$1`` aborts:
#: an empty ``$d`` would chmod the host's ``/usr``. ``p`` follows dh_compress's
#: ``.gz`` rename and skips a path dh_usrlocal removed.
_FIXPERMS_HEADER = (
    "#!/bin/sh\n"
    "# Generated by pkgforge dbdump -f debian. Usage: sh fixperms DEBIAN-DIR\n"
    "set -e\n"
    "d=${1:?usage: sh fixperms DEBIAN-DIR}\n"
    "p() {\n"
    '  for f in "$1" "$1.gz"; do\n'
    '    if [ -e "$f" ] || [ -L "$f" ]; then printf \'%s\\n\' "$f"; return; fi\n'
    "  done\n"
    '  echo "fixperms: skipping missing $1" >&2\n'
    "  return 1\n"
    "}\n"
)


#: The line that marks a file this format wrote: the first line of a list, the
#: line after the shebang of a script.
_MARKER = "# Generated by pkgforge dbdump -f debian"
#: The artifacts that carry the marker, by the name debhelper knows them
#: (``PKG.install`` is ``install``): one is never written over a file without it.
_MARKED = frozenset(
    ("install", "dirs", "not-installed", "postinst", "postrm", "fixperms")
)
#: The per-package files debhelper ignores in their nameless form once the
#: package-named one exists.
_NAMELESS_IGNORED = ("install", "dirs", "conffiles", "postinst", "postrm")
_SCRIPT_HEADER = f"#!/bin/sh\n{_MARKER}\nset -e\n\n#DEBHELPER#\n"
_GHOST = FileKind.Ghost.value
_CONFIG_KINDS = frozenset((FileKind.Config.value, FileKind.ConfigNoReplace.value))
_WHITESPACE_RE = re.compile(r"\s")
#: A dpkg-gencontrol variable: it replaces one in every control field, and no
#: escape keeps the text as written.
_SUBSTVAR_RE = re.compile(r"\$\{[-:0-9A-Za-z]+\}")
#: The ``[package]`` keys, and the ``[[packages]]`` ones, that reach ``control``
#: as free text.
_CONTROL_TEXT = ("summary", "description", "homepage", "maintainer")
#: ``dpkg-statoverride --list`` matches its argument with fnmatch(3), so these
#: characters of a path are backslash-escaped there; ``--add`` and ``--remove``
#: take the path as written.
_FNMATCH_SPECIAL_RE = re.compile(r"([\\*?[])")


def _sh_word(value: str) -> str:
    """Quote ``value`` for POSIX ``sh`` (a DB path: always distinct, so this
    is never cached -- see :func:`_sh_word_cached` for owner/group/mode)."""
    return shlex.quote(value)


@functools.lru_cache(maxsize=256)
def _sh_word_cached(value: str) -> str:
    """Cached :func:`_sh_word`, for owner/group/mode values that repeat
    across many entries (unlike a path, which is unique per entry)."""
    return shlex.quote(value)


def _install_time(owner: str, group: str) -> bool:
    """Whether the owner or group is one the package creates or relies on a
    dependency for: not a base-passwd name, so it does not exist while dpkg
    unpacks and ``postinst`` has to apply it."""
    return (owner != DEFAULT and owner not in BASE_USERS) or (
        group != DEFAULT and group not in BASE_GROUPS
    )


def _fixperms_line(
    package: str, path: str, mode: str, owner: str, group: str, is_symlink: bool
) -> str:
    """Render PATH's one line, in ``package``'s directory, for the generated
    ``fixperms`` script (only
    ever called once a caller already knows at least one of mode/owner/group
    is pinned): resolve the path with ``p`` and, when it exists, run its
    ``chown``/``chgrp``/``chmod``. Owner and group both pinned
    become one ``chown -- owner:group``; only one pinned uses ``chown`` or
    ``chgrp``.

    Order matches :func:`~pkgforge.entry.apply_entry`: owner (and
    group) before mode, since ``chown`` clears a regular file's setuid/setgid
    bit even to the same owner. ``-h`` targets the symlink itself for
    ``chown``/``chgrp`` (never its target); ``chmod`` is never emitted for a
    symlink at all -- POSIX ``chmod`` has no ``-h`` and would follow the
    link. ``--`` keeps an owner/group/mode that looks like an option (e.g.
    ``-x``) from being read as one.
    """
    target = '"$t"'
    flag = "-h " if is_symlink else ""
    lines = []
    if owner != DEFAULT and group != DEFAULT:
        owner_group = _sh_word_cached(f"{owner}:{group}")
        lines.append(f"chown {flag}-- {owner_group} {target}")
    elif owner != DEFAULT:
        lines.append(f"chown {flag}-- {_sh_word_cached(owner)} {target}")
    elif group != DEFAULT:
        lines.append(f"chgrp {flag}-- {_sh_word_cached(group)} {target}")
    if mode != DEFAULT and not is_symlink:
        lines.append(f"chmod -- {_sh_word_cached(mode)} {target}")
    # `if`, not `&&`: a skipped path must leave the script's exit status 0.
    return f"if t=$(p \"$d\"/{_sh_word(package + path)}); then {'; '.join(lines)}; fi"


def _marked(lines: typing.List[str]) -> bytes:
    """A list file: the marker line, then one ``lines`` entry per line."""
    text = _MARKER + "\n" + "".join(line + "\n" for line in lines)
    return text.encode("utf-8", "surrogateescape")


def _plain(lines: typing.List[str]) -> bytes:
    """A list file with no marker (debhelper reads a ``conffiles`` comment
    as a file name)."""
    text = "".join(line + "\n" for line in lines)
    return text.encode("utf-8", "surrogateescape")


def _has_marker(path: Path) -> bool:
    head = path.read_bytes()[:1024].decode("utf-8", "replace")
    return any(line.startswith(_MARKER) for line in head.splitlines()[:2])


def _check_existing(artifacts: typing.Dict[str, bytes], output: Path) -> None:
    """Raise :class:`UsageError` when writing ``artifacts`` into ``output``
    would replace or shadow a debhelper file somebody wrote by hand: a marked
    artifact whose existing file lacks the marker, a nameless file debhelper
    ignores beside the package-named one, or a ``conffiles`` line the new file
    would drop. Nothing is written when any applies."""
    main = next(
        (name[: -len(".install")] for name in artifacts if name.endswith(".install")),
        "",
    )
    for name in artifacts:
        path = output / name
        if (
            name.rpartition(".")[2] in _MARKED
            and path.is_file()
            and not _has_marker(path)
        ):
            raise UsageError(
                f"{path} was not generated by pkgforge; refusing to "
                "overwrite it: merge the generated lines by hand, or "
                "dump into another directory"
            )
    for nameless in _NAMELESS_IGNORED:
        path = output / nameless
        if path.is_file():
            raise UsageError(
                f"{path} is ignored by debhelper once debian/{main}.{nameless} "
                "exists: move its lines there (or into pkgforge.cfg) and "
                "delete it"
            )
    for name, data in artifacts.items():
        path = output / name
        if not name.endswith(".conffiles") or not path.is_file():
            continue
        kept = set(data.decode("utf-8", "surrogateescape").splitlines())
        text = path.read_bytes().decode("utf-8", "surrogateescape")
        for line in text.splitlines():
            if line.strip() and line not in kept:
                raise UsageError(
                    f"{path}: dumping would drop {line}: mark that file "
                    "config, or delete the line"
                )


#: The files ``--skeleton`` adds: the user edits them, so they are written only
#: when missing.
_SKELETON_FILES = frozenset(("control", "changelog", "rules", "source/format"))
_NO_CFG = (
    "--skeleton needs the path of pkgforge.cfg: give --config, PKGFORGE_CONFIG "
    "or ./pkgforge.cfg"
)


def _description_lines(summary: str, text: typing.Optional[str]) -> str:
    """The ``Description`` field: the synopsis, then the long description's
    lines, each space-prefixed (an empty one as ``.``)."""
    lines = [f"Description: {summary}"]
    for line in (text or "").splitlines():
        lines.append(f" {line}" if line.strip() else " .")
    return "\n".join(lines) + "\n"


def _refuse_substvars(config: ProjectConfig) -> None:
    """Raise :class:`UsageError` for a ``${NAME}`` in the free text of
    ``[package]`` or a ``[[packages]]`` element, which dpkg-gencontrol would
    replace."""
    tables = [("[package]", config.package)]
    tables.extend((f"[[packages]] {sub.name}", sub) for sub in config.packages)
    for where, table in tables:
        for key in _CONTROL_TEXT:
            match = _SUBSTVAR_RE.search(getattr(table, key, None) or "")
            if match:
                raise UsageError(
                    f"debian --skeleton: {where} {key} holds {match.group(0)}, "
                    "which dpkg-gencontrol replaces and cannot escape: reword it"
                )


def _control(context: DumpContext) -> str:
    """The ``control`` file: the source stanza, then one stanza per package."""
    config = context.config
    main = config.package
    assert main is not None
    _refuse_substvars(config)
    main_arch = "all" if main.arch == "all" else "any"
    source = [
        f"Source: {main.name}",
        f"Section: {main.debian.section or 'misc'}",
        f"Priority: {main.debian.priority or 'optional'}",
        f"Maintainer: {main.maintainer}",
        "Build-Depends: debhelper-compat (= 13), dh-sequence-installsysusers",
        "Rules-Requires-Root: binary-targets",
        "Standards-Version: 4.7.0",
    ]
    if main.homepage:
        source.append(f"Homepage: {main.homepage}")
    stanzas = ["\n".join(source) + "\n"]
    packages = [
        (main.name, main_arch, None, main.debian, main.summary, main.description)
    ]
    for sub in config.packages:
        arch = "all" if (sub.arch or main_arch) == "all" else "any"
        packages.append((sub.name, arch, sub, sub.debian, sub.summary, sub.description))
    for name, arch, sub, debian, summary, description in packages:
        fields = [f"Package: {name}", f"Architecture: {arch}"]
        if sub is not None:
            if debian.section:
                fields.append(f"Section: {debian.section}")
            if debian.priority:
                fields.append(f"Priority: {debian.priority}")
        depends = ["${misc:Depends}"]
        if arch == "any":
            depends.append("${shlibs:Depends}")
        depends.append("${pkgforge:Depends}")
        depends.extend(debian.depends)
        fields.append(f"Depends: {', '.join(depends)}")
        stanzas.append(
            "\n".join(fields) + "\n" + _description_lines(summary or "", description)
        )
    return "\n".join(stanzas)


def _changelog(context: DumpContext) -> str:
    main = context.config.package
    assert main is not None
    epoch = _source_date_epoch()
    moment = (
        datetime.datetime.fromtimestamp(epoch, datetime.timezone.utc)
        if epoch is not None
        else datetime.datetime.now(datetime.timezone.utc)
    )
    version = f"{main.version}-{main.release}" if main.release else main.version
    return (
        f"{main.name} ({version}) unstable; urgency=medium\n\n"
        "  * Generated by pkgforge from pkgforge.cfg.\n\n"
        f" -- {main.maintainer}  {email.utils.format_datetime(moment)}\n"
    )


def _rules(context: DumpContext) -> str:
    """``debian/rules``: stage into ``debian/tmp`` after ``dh_prep``, dump the
    package files, and apply the pinned permissions after ``dh_fixperms``."""
    if context.config_path is None:
        raise UsageError(_NO_CFG)
    cfg = context.config_path.resolve()
    output = context.output
    assert output is not None  # _skeleton: a skeleton needs a directory OUTPUT
    # The source root is OUTPUT's parent. Resolving that existing directory, not
    # the OUTPUT that may not exist yet, spells it as `cfg` is spelled.
    if output.name in ("", ".", ".."):
        root = output.resolve().parent
    else:
        root = output.parent.resolve()
    try:
        ref = cfg.relative_to(root).as_posix()
    except ValueError:
        ref = cfg.as_posix()
    # `$` is make's escape character; the shell sees the quoted name.
    cfg_arg = shlex.quote(ref).replace("$", "$$")
    return (
        "#!/usr/bin/make -f\n"
        "# Stages into debian/tmp from pkgforge.cfg and records the file DB. The\n"
        "# dump runs after dh_prep, so the substitution variable\n"
        "# ${pkgforge:Depends} in debian/control is defined. Needs pkgforge on PATH.\n"
        "export PKGFORGE_ROOT := $(CURDIR)/debian/tmp\n"
        "export PKGFORGE_DB := $(CURDIR)/debian/pkgforge.jsonl\n"
        "\n"
        "%:\n"
        "\tdh $@\n"
        "\n"
        "override_dh_auto_install:\n"
        f"\tpkgforge -q --config {cfg_arg} stage --init\n"
        f"\tpkgforge -q --config {cfg_arg} dbdump -f debian debian/\n"
        "\tdh_installdirs\n"
        "\n"
        "override_dh_fixperms:\n"
        "\tdh_fixperms\n"
        "\tsh debian/fixperms debian\n"
    )


def _skeleton(context: DumpContext) -> typing.Dict[str, bytes]:
    """The skeleton files, rendered from ``context``."""
    if context.output is None:
        raise UsageError("--skeleton writes into a directory")
    _require_keys(
        "debian --skeleton",
        context.config,
        ("version", "summary", "maintainer"),
        ("summary",),
    )
    main = context.config.package
    assert main is not None
    texts = {
        "control": _control(context),
        "changelog": _changelog(context),
        "rules": _rules(context),
        "source/format": "3.0 (quilt)\n" if main.release else "3.0 (native)\n",
    }
    return {name: text.encode("utf-8") for name, text in texts.items()}


class _Package(typing.NamedTuple):
    """One package's lines, before they are joined into files."""

    install: typing.List[str]
    dirs: typing.List[str]
    conffiles: typing.List[str]
    not_installed: typing.List[str]
    fixperms: typing.List[str]
    overrides: typing.List[str]
    purges: typing.List[str]
    setcaps: typing.List[str]


def _package_lines(name: str, entries: FileEntries) -> _Package:
    """The ``install``, ``dirs``, ``conffiles``, ``fixperms`` and script lines
    of the package ``name`` from its ``entries``."""
    result = _Package([], [], [], [], [], [], [], [])
    for path, entry in entries:
        mode = _or_default(entry["mode"])
        owner = _or_default(entry["owner"])
        group = _or_default(entry["group"])
        is_symlink = entry["type"] == FileType.Symlink
        rel = path.lstrip("/")
        fkind = entry["kind"]
        if fkind == _GHOST:
            # Owned by the package, shipped by nothing: dh_missing must
            # not see the staged file, and dh_installdirs must not
            # create the directory.
            if entry["type"] != FileType.Directory:
                result.not_installed.append(_dh_src(rel))
            continue
        if fkind in _CONFIG_KINDS and not path.startswith("/etc/"):
            if _WHITESPACE_RE.search(path):
                raise DumpError(f"debian: conffile {path} contains whitespace")
            result.conffiles.append(path)
        override = _install_time(owner, group)
        if override:
            if is_symlink:
                raise DumpError(
                    f"debian: {path} is a symlink owned by an account the "
                    "package creates; dpkg-statoverride would follow it"
                )
            if mode == DEFAULT:
                raise DumpError(
                    f"debian: {path} is owned by an account the package "
                    "creates and needs a recorded mode for dpkg-statoverride"
                )
            word = _sh_word(path)
            pattern = _sh_word(_FNMATCH_SPECIAL_RE.sub(r"\\\1", path))
            result.overrides.append(
                f"  if ! dpkg-statoverride --list {pattern} >/dev/null; then "
                f"dpkg-statoverride --update --add "
                f"{_sh_word_cached(owner if owner != DEFAULT else 'root')} "
                f"{_sh_word_cached(group if group != DEFAULT else 'root')} "
                f"{_sh_word_cached(mode)} {word}; fi"
            )
            result.purges.append(
                f"  if dpkg-statoverride --list {pattern} >/dev/null; then "
                f"dpkg-statoverride --remove {word}; fi"
            )
        caps = entry["caps"]
        if caps != DEFAULT:
            # No `--`: setcap reads it as the capability text. A capability
            # string never starts with `-`, so nothing needs protecting.
            result.setcaps.append(
                f'  setcap {_sh_word_cached(caps)} "$DPKG_ROOT"{_sh_word(path)}'
            )
        if entry["type"] == FileType.Directory:
            dline = _dh_dest(rel)
            # dh_installdirs reads a leading "#" as a comment and never globs,
            # so a "./" prefix keeps the name literal without escaping it.
            if dline.startswith("#"):
                dline = "./" + dline
            result.dirs.append(dline)
        else:
            # rel is relative, so the rpartition equals posixpath.dirname.
            dest = _dh_dest(rel.rpartition("/")[0].rstrip("/"))
            result.install.append(f"{_dh_src(rel)} {dest}".rstrip())
        if not override and (mode != DEFAULT or owner != DEFAULT or group != DEFAULT):
            result.fixperms.append(
                _fixperms_line(name, path, mode, owner, group, is_symlink)
            )
    return result


class DebianFiles(MultiArtifactFormat):
    """Debian packaging artifacts built from surviving DB entries, named for
    the packages ``pkgforge.cfg`` declares (``[package]`` and
    ``[[packages]]``; ``[package] name`` is required). For each package ``P``:

    * ``P.install`` -- ``dh_install``-style lines ``<src> <dest-dir>`` (the
      source is the build-root-relative path, debhelper-escaped; the
      destination is the entry's parent directory, escaped for ``$``/space
      only), one per non-directory entry;
    * ``P.dirs`` -- ``dh_installdirs``-style lines (dest-escaped, one per
      directory entry, in every case -- an already-populated directory is a
      harmless duplicate `mkdir`), so a directory recorded empty (``install
      -d``) still reaches the package; never routed through ``install``,
      which would re-copy any children ``--exclude`` dropped;
    * ``P.conffiles`` -- the ``config`` and ``config-noreplace`` entries outside
      ``/etc/`` (debhelper adds those under ``/etc/`` itself), one absolute
      path per line; whitespace in such a path raises
      :class:`~pkgforge.exceptions.DumpError`;
    * ``P.postinst`` -- a maintainer script with ``#DEBHELPER#``; on
      ``configure`` it runs, for each entry owned by an account the package
      creates (an owner or group outside the base-passwd set), a guarded
      ``dpkg-statoverride --update --add`` and then, for each entry with
      ``caps``, a ``setcap`` line;
    * ``P.postrm`` -- the same header; on ``purge`` it removes those overrides;
    * ``P.substvars`` -- ``pkgforge:Depends=libcap2-bin`` when ``P`` has an entry
      with ``caps``, else an empty value, for ``Depends: ${pkgforge:Depends}``.
      ``dh_prep`` deletes this file, so it only takes effect when the dump
      runs after ``dh_prep`` (``override_dh_auto_install``).

    And once for the source:

    * ``not-installed`` -- the ghost entries of every package that are not
      directories, sorted, in ``install``'s source escaping, so ``dh_missing
      --fail-missing`` accepts a ghost file left in the staging directory
      (debhelper reads only the source-wide file);
    * ``fixperms`` -- a POSIX ``sh`` script, always written, that applies
      every pinned mode/owner/group directly to the package directories: run
      it from ``override_dh_fixperms`` (after ``dh_fixperms``, which would
      otherwise strip the very bits this pins) as ``sh debian/fixperms
      debian``. Per pinned entry: one ``chown owner:group`` (or
      ``chown``/``chgrp`` when only one is pinned), then ``chmod`` (chown
      before chmod, since chown clears a regular file's setuid/setgid bit
      even to the same owner); a symlink
      gets ``chown -h``/``chgrp -h`` and never a ``chmod`` (POSIX ``chmod``
      has no ``-h`` and would follow the link to a target outside the
      package tree). A path that dh_compress renamed to ``<path>.gz`` is
      found there; one that is gone (dh_usrlocal) is reported on stderr and
      skipped. With no pinned entry, the script is just its own header.

    With ``skeleton`` (``dbdump --skeleton``) it also writes the files you edit:
    ``control`` (a stanza per package, ``Depends`` listing
    ``${pkgforge:Depends}``), ``changelog`` (dated ``SOURCE_DATE_EPOCH``, else
    the current time), ``rules`` (the ``debian/tmp`` recipe, naming the project
    file, mode 755) and ``source/format``. They need a directory OUTPUT, the
    project file's path and ``[package]`` ``version``, ``summary`` and
    ``maintainer``; one that exists is kept with a warning unless ``force``.
    A ``${NAME}`` in the ``summary``, ``description``, ``homepage`` or
    ``maintainer`` of any package is :class:`~pkgforge.exceptions.UsageError`:
    dpkg-gencontrol replaces it and nothing escapes it.

    Every artifact is written for every declared package, so no stale one
    survives. Writing refuses, before it writes anything: an existing
    ``install``, ``dirs``, ``not-installed``, ``postinst``, ``postrm`` or
    ``fixperms`` without the marker line this format puts first (a hand-written
    file); a nameless ``install``, ``dirs``, ``conffiles``, ``postinst`` or
    ``postrm`` in the directory, which debhelper ignores once the
    package-named file exists; and an existing ``P.conffiles`` that lists a
    path the new one lacks.

    The build needs ``dh $@ --with installsysusers`` (debhelper 13.10+) or
    ``Build-Depends: dh-sequence-installsysusers`` so the accounts exist
    before ``postinst`` applies the overrides.

    Ghost entries are left out of ``install``, ``dirs`` and ``fixperms``, and
    so are entries owned by an account the package creates: dpkg unpacks them
    before ``postinst`` can create the account, so ``fixperms`` leaves them
    root-owned and the override applies them. Such a symlink, or one with no
    recorded mode, raises :class:`~pkgforge.exceptions.DumpError`.

    A path with a control character raises
    :class:`~pkgforge.exceptions.DumpError` while the artifacts are built in
    memory; they are written only after :meth:`render` returns, so nothing
    partial is left behind.
    """

    NAME = "debian"
    ALIASES = ("deb",)
    SKELETON = True

    def render(
        self, entries: FileEntries, context: DumpContext
    ) -> typing.Dict[str, bytes]:
        if context.config.package is None:
            raise UsageError(
                "dbdump -f debian names its files after [package] name: "
                "set it in pkgforge.cfg"
            )
        files = self._render_package_files(entries, context)
        if self.skeleton:
            files.update(_skeleton(context))
        return files

    def _render_package_files(
        self, entries: FileEntries, context: DumpContext
    ) -> typing.Dict[str, bytes]:
        groups = _packages(entries, context.config)
        # A control character in a path is the one rule debian adds to the
        # shared entry validation: one batch search, a per-entry pass on a hit.
        paths = [path for path, _entry in entries]
        if _has_control(paths):
            for path in paths:
                _reject_control(path, "debian")

        files: typing.Dict[str, bytes] = {}
        not_installed: typing.List[str] = []
        fixperms: typing.List[str] = []
        for name, group in groups:
            lines = _package_lines(name, group)
            not_installed.extend(lines.not_installed)
            fixperms.extend(lines.fixperms)
            postinst = _SCRIPT_HEADER
            if lines.overrides or lines.setcaps:
                # chown drops file capabilities, so the overrides come first.
                configure = [
                    'if [ "$1" = configure ]; then',
                    *lines.overrides,
                    *lines.setcaps,
                    "fi",
                ]
                postinst += "\n".join(configure) + "\n"
            postrm = _SCRIPT_HEADER
            if lines.purges:
                purge = ['if [ "$1" = purge ]; then', *lines.purges, "fi"]
                postrm += "\n".join(purge) + "\n"
            depends = (
                "pkgforge:Depends=libcap2-bin"
                if lines.setcaps
                else ("pkgforge:Depends=")
            )
            files[f"{name}.install"] = _marked(lines.install)
            files[f"{name}.dirs"] = _marked(lines.dirs)
            files[f"{name}.conffiles"] = _plain(lines.conffiles)
            files[f"{name}.postinst"] = postinst.encode("utf-8", "surrogateescape")
            files[f"{name}.postrm"] = postrm.encode("utf-8", "surrogateescape")
            files[f"{name}.substvars"] = _marked([depends])
        files["not-installed"] = _marked(sorted(not_installed))
        files["fixperms"] = _FIXPERMS_HEADER.encode(
            "utf-8", "surrogateescape"
        ) + _plain(fixperms)
        return files

    def write(
        self, rendered: Rendered, output: Path, *, force: bool = False
    ) -> typing.List[Path]:
        """As for any multi-artifact format, after refusing a directory whose
        existing files this dump would replace or shadow (see the class). A
        skeleton file that exists is kept unless ``force``; ``rules`` is made
        executable."""
        artifacts = typing.cast(typing.Dict[str, bytes], rendered)
        _check_existing(artifacts, output)
        files = {
            output / name: data
            for name, data in artifacts.items()
            if name not in _SKELETON_FILES
        }
        files.update(
            _keep_existing(
                {
                    output / name: data
                    for name, data in artifacts.items()
                    if name in _SKELETON_FILES
                },
                force,
            )
        )
        for directory in {path.parent for path in files}:
            directory.mkdir(parents=True, exist_ok=True)
        _write_files(files)
        if output / "rules" in files:
            (output / "rules").chmod(0o755)
        return list(files)
