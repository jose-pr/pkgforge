"""The ``sysusers.d`` and ``tmpfiles.d`` files a package needs, as text.

Both are payload files: rpm 4.19+ acts on a shipped sysusers file by itself,
debhelper's ``dh_installsysusers`` and ``dh_installtmpfiles`` find them in the
package, and a direct packager reads them from the build root.
"""

from __future__ import annotations

import re
import typing

from .config import ProjectConfig
from .entry import DEFAULT, FileEntries, FileKind, FileType
from .exceptions import UsageError

SYSUSERS_DIR = "/usr/lib/sysusers.d"
TMPFILES_DIR = "/usr/lib/tmpfiles.d"
UNIT_DIR = "/usr/lib/systemd/system"

_HEADER = "# Generated by pkgforge from pkgforge.cfg; do not edit.\n"
#: What a tmpfiles.d path field cannot hold unquoted: systemd-tmpfiles reads
#: either quote as the start of a quoted word (a lone ``'`` fails the line).
_UNSPELLABLE_RE = re.compile(r'[\s"\'\\\x00-\x1f\x7f]')
_GHOST = FileKind.Ghost.value
_UNIT_SUFFIXES = (".service", ".socket", ".timer", ".path")


def _percent(text: str) -> str:
    """``text`` with ``%`` doubled: both file formats expand ``%`` specifiers."""
    return text.replace("%", "%%")


def sysusers_text(config: ProjectConfig) -> str:
    """The ``sysusers.d`` file for the accounts ``config`` creates: a ``g`` line
    per created group, a ``u`` line per created user (which also makes the
    group of the same name), then an ``m`` line per supplementary group.
    ``""`` when it creates none."""
    lines = [f"g {_percent(group.name)} -" for group in config.groups if group.create]
    members = []
    for user in config.users:
        if not user.create:
            continue
        name = _percent(user.name)
        gecos = f'"{_percent(user.description)}"' if user.description else "-"
        home = _percent(user.home) if user.home else "-"
        shell = _percent(user.shell) if user.shell else "-"
        lines.append(f"u {name} - {gecos} {home} {shell}")
        members.extend(f"m {name} {_percent(group)}" for group in user.groups)
    lines.extend(members)
    return _HEADER + "\n".join(lines) + "\n" if lines else ""


def created_accounts(
    config: ProjectConfig,
) -> typing.Tuple[typing.Set[str], typing.Set[str]]:
    """The user and group names ``config`` creates; a created user also makes
    the group of its name."""
    users = {user.name for user in config.users if user.create}
    groups = {group.name for group in config.groups if group.create} | users
    return users, groups


def tmpfiles_text(entries: FileEntries) -> str:
    """The ``tmpfiles.d`` file that creates each ghost directory of ``entries``
    at install time (``d PATH MODE OWNER GROUP -``), sorted by path. ``""`` when
    there is none.

    Raises:
        UsageError: a ghost directory's path is one ``tmpfiles.d`` cannot spell
            (whitespace, ``"``, ``'``, a backslash or a control character).
    """
    lines = []
    for path, entry in sorted(entries, key=lambda pathentry: pathentry[0]):
        if entry["kind"] != _GHOST or entry["type"] != FileType.Directory:
            continue
        if _UNSPELLABLE_RE.search(path):
            raise UsageError(f"{path}: a ghost directory path tmpfiles.d cannot spell")
        mode = entry["mode"]
        mode = "-" if mode == DEFAULT else format(int(mode, 8), "04o")
        lines.append(
            f"d {_percent(path)} {mode} {entry['owner'] or DEFAULT} "
            f"{entry['group'] or DEFAULT} -"
        )
    return _HEADER + "\n".join(lines) + "\n" if lines else ""


def unit_names(entries: FileEntries) -> typing.List[str]:
    """The systemd units ``entries`` ship, sorted: the live regular files
    directly in :data:`UNIT_DIR` named ``*.service``, ``*.socket``, ``*.timer``
    or ``*.path``. A template (``NAME@.service``) and a ghost entry are not
    units a package enables."""
    names = []
    for path, entry in entries:
        if entry["kind"] == _GHOST or entry["type"] != FileType.File:
            continue
        parent, _, name = path.rpartition("/")
        if parent == UNIT_DIR and name.endswith(_UNIT_SUFFIXES) and "@." not in name:
            names.append(name)
    return sorted(names)
