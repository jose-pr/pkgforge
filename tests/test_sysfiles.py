"""The generated ``sysusers.d`` and ``tmpfiles.d`` files: their text,
``Project.sysfiles``, ``pkgforge sysfiles`` and ``stage``."""

from __future__ import annotations

import logging
import typing
from pathlib import Path

import pytest

from pkgforge import Project, UsageError
from pkgforge._sysfiles import sysusers_text, tmpfiles_text
from pkgforge.config import GroupAccount, PackageInfo, ProjectConfig, UserAccount
from pkgforge.db import open_db

HEADER = "# Generated by pkgforge from pkgforge.cfg; do not edit.\n"
SYSUSERS = "usr/lib/sysusers.d/hi.conf"
TMPFILES = "usr/lib/tmpfiles.d/hi.conf"


def config(*, users=(), groups=(), package: typing.Optional[str] = "hi"):
    return ProjectConfig(
        package=None if package is None else PackageInfo(package),
        users=tuple(users),
        groups=tuple(groups),
    )


def ghost_dir(mode="755", owner="svc", group="svc", **over):
    return {
        "mode": mode,
        "owner": owner,
        "group": group,
        "type": "directory",
        "kind": "ghost",
        "caps": "-",
        "package": "-",
        "meta": {},
        **over,
    }


def live(db: Path) -> typing.Dict[str, typing.Any]:
    return {path: e for path, e in open_db(db).load().items() if e is not None}


def seed(db: Path, **paths) -> None:
    """Write ``{dbpath: entry}`` (keys spelled with ``__`` for ``/``) to a DB."""
    provider = open_db(db)
    provider.init()
    for key, value in paths.items():
        provider.add("/" + key.replace("__", "/"), value)


# -- sysusers.d --------------------------------------------------------------


def test_sysusers_text_lists_groups_then_users_then_members():
    cfg = config(
        users=[
            UserAccount("svc", description="a service", home="/var/lib/svc"),
            UserAccount("other", shell="/sbin/nologin", groups=("adm", "extra")),
        ],
        groups=[GroupAccount("extra")],
    )
    assert sysusers_text(cfg) == (
        HEADER + "g extra -\n"
        'u svc - "a service" /var/lib/svc -\n'
        "u other - - - /sbin/nologin\n"
        "m other adm\n"
        "m other extra\n"
    )


def test_sysusers_text_skips_accounts_that_already_exist():
    cfg = config(
        users=[UserAccount("dep", create=False)],
        groups=[GroupAccount("depg", create=False)],
    )
    assert sysusers_text(cfg) == ""


def test_sysusers_text_is_empty_without_accounts():
    assert sysusers_text(config()) == ""


def test_sysusers_text_doubles_percent():
    cfg = config(users=[UserAccount("svc", description="50% off", home="/srv/100%")])
    assert 'u svc - "50%% off" /srv/100%% -' in sysusers_text(cfg)


# -- tmpfiles.d --------------------------------------------------------------


def test_tmpfiles_text_lists_ghost_directories_sorted():
    entries = [
        ("/run/b", ghost_dir("750", "svc", "adm")),
        ("/run/a", ghost_dir("-", "-", "-")),
        ("/run/c", ghost_dir("4755")),
        ("/var/lib/real", ghost_dir(kind="file")),
        ("/run/file", ghost_dir(type="file")),
    ]
    assert tmpfiles_text(entries) == (
        HEADER + "d /run/a - - - -\n"
        "d /run/b 0750 svc adm -\n"
        "d /run/c 4755 svc svc -\n"
    )


def test_tmpfiles_text_is_empty_without_ghost_directories():
    assert tmpfiles_text([("/etc/a", ghost_dir(kind="file"))]) == ""


def test_tmpfiles_text_doubles_percent():
    assert "d /run/100%%" in tmpfiles_text([("/run/100%", ghost_dir())])


@pytest.mark.parametrize("path", ["/run/a b", '/run/a"b', "/run/a\\b", "/run/a\tb"])
def test_tmpfiles_text_refuses_a_path_it_cannot_spell(path):
    with pytest.raises(UsageError, match="a ghost directory path tmpfiles.d cannot"):
        tmpfiles_text([(path, ghost_dir())])


# -- Project.sysfiles --------------------------------------------------------


def test_sysfiles_writes_and_records_both_files(tmp_path):
    root, db = tmp_path / "root", tmp_path / "f.jsonl"
    seed(db, run__hi=ghost_dir())
    cfg = config(users=[UserAccount("svc", description="hi svc")])
    records = Project(root, db, config=cfg).sysfiles()

    assert [path for path, _e in records] == [
        "/usr/lib/sysusers.d/hi.conf",
        "/usr/lib/tmpfiles.d/hi.conf",
    ]
    sysusers = (root / SYSUSERS).read_bytes().decode()
    assert 'u svc - "hi svc" - -\n' in sysusers
    assert "d /run/hi 0755 svc svc -\n" in (root / TMPFILES).read_bytes().decode()
    recorded = live(db)
    expected = {
        "mode": "644",
        "owner": "root",
        "group": "root",
        "type": "file",
        "kind": "file",
        "caps": "-",
        "package": "hi",
        "meta": {},
    }
    assert recorded["/usr/lib/sysusers.d/hi.conf"] == expected
    assert recorded["/usr/lib/tmpfiles.d/hi.conf"] == expected


def test_sysfiles_twice_changes_nothing(tmp_path):
    root, db = tmp_path / "root", tmp_path / "f.jsonl"
    seed(db, run__hi=ghost_dir())
    project = Project(root, db, config=config(users=[UserAccount("svc")]))
    project.sysfiles()
    first = (root / TMPFILES).read_bytes()
    project.sysfiles()
    assert (root / TMPFILES).read_bytes() == first
    assert len(live(db)) == 3


def test_sysfiles_writes_only_the_file_that_has_lines(tmp_path):
    root, db = tmp_path / "root", tmp_path / "f.jsonl"
    seed(db)
    records = Project(root, db, config=config(users=[UserAccount("svc")])).sysfiles()
    assert [path for path, _e in records] == ["/usr/lib/sysusers.d/hi.conf"]
    assert not (root / TMPFILES).exists()


def test_sysfiles_removes_a_file_it_no_longer_needs(tmp_path):
    root, db = tmp_path / "root", tmp_path / "f.jsonl"
    seed(db, run__hi=ghost_dir())
    Project(root, db, config=config(users=[UserAccount("svc")])).sysfiles()
    assert (root / SYSUSERS).exists()

    records = Project(root, db, config=config()).sysfiles()
    assert records[0] == ("/usr/lib/sysusers.d/hi.conf", None)
    assert [path for path, _e in records] == [
        "/usr/lib/sysusers.d/hi.conf",
        "/usr/lib/tmpfiles.d/hi.conf",
    ]
    assert not (root / SYSUSERS).exists()
    assert set(live(db)) == {"/run/hi", "/usr/lib/tmpfiles.d/hi.conf"}


def test_sysfiles_without_a_package_name_is_refused(tmp_path):
    root, db = tmp_path / "root", tmp_path / "f.jsonl"
    seed(db, run__hi=ghost_dir())
    with pytest.raises(UsageError, match="needs .package. name"):
        Project(root, db, config=config(package=None)).sysfiles()
    assert not (root / "usr").exists()


def test_sysfiles_with_nothing_to_write_does_nothing(tmp_path):
    root, db = tmp_path / "root", tmp_path / "f.jsonl"
    seed(db)
    assert Project(root, db, config=config(package=None)).sysfiles() == []


def test_sysfiles_without_a_file_db_returns_the_records(tmp_path):
    cfg = config(users=[UserAccount("svc")])
    records = Project(tmp_path / "root", config=cfg).sysfiles()
    assert [path for path, _e in records] == ["/usr/lib/sysusers.d/hi.conf"]
    assert (tmp_path / "root" / SYSUSERS).is_file()


def test_sysfiles_logs_one_line_per_file(tmp_path, caplog):
    root, db = tmp_path / "root", tmp_path / "f.jsonl"
    seed(db, run__hi=ghost_dir())
    project = Project(root, db, config=config(users=[UserAccount("svc")]))
    with caplog.at_level(logging.INFO, logger="pkgforge.sysfiles"):
        project.sysfiles()
    assert [r.getMessage() for r in caplog.records] == [
        "wrote /usr/lib/sysusers.d/hi.conf",
        "wrote /usr/lib/tmpfiles.d/hi.conf",
    ]


def test_the_sysfiles_command_writes_the_files(cli, tmp_path):
    cfg = tmp_path / "pkgforge.cfg"
    cfg.write_bytes(b'[package]\nname = "hi"\n\n[[users]]\nname = "svc"\n')
    db = tmp_path / "f.jsonl"
    seed(db)
    result = cli(
        "--config",
        str(cfg),
        "--buildroot",
        str(tmp_path / "root"),
        "--db",
        str(db),
        "sysfiles",
    )
    assert result.rc == 0, result.err
    assert "u svc - - - -\n" in (tmp_path / "root" / SYSUSERS).read_text()
    assert "/usr/lib/sysusers.d/hi.conf" in live(db)


# -- stage -------------------------------------------------------------------

STAGE_CFG = """\
[package]
name = "hi"

[[users]]
name = "svc"
home = "/var/lib/hi"

[[stage]]
dir = "/var/lib/hi"
owner = "svc"
group = "svc"
mode = "750"

[[stage]]
dir = "/run/hi"
kind = "ghost"
owner = "svc"
group = "svc"
mode = "755"
"""


@pytest.mark.posix
def test_stage_generates_the_system_files(cli, tmp_path, caplog):
    cfg = tmp_path / "pkgforge.cfg"
    cfg.write_bytes(STAGE_CFG.encode("utf-8"))
    db = tmp_path / "f.jsonl"
    with caplog.at_level(logging.INFO, logger="pkgforge.stage"):
        result = cli(
            "--config",
            str(cfg),
            "--buildroot",
            str(tmp_path / "root"),
            "--db",
            str(db),
            "stage",
            "--init",
        )
    assert result.rc == 0, result.err
    assert set(live(db)) == {
        "/var/lib/hi",
        "/run/hi",
        "/usr/lib/sysusers.d/hi.conf",
        "/usr/lib/tmpfiles.d/hi.conf",
    }
    assert "d /run/hi 0755 svc svc -\n" in (tmp_path / "root" / TMPFILES).read_text()
    messages = [r.getMessage() for r in caplog.records]
    assert "generated 2 system file(s)" in messages
    assert messages[-1] == "staged 2 step(s), 4 record(s)"
