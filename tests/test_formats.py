@pytest.mark.posix
def test_debian_fixperms_script_applies_pins(tmp_path, monkeypatch):
    skip_if_fs_rejects_non_utf8(tmp_path)
    # The host's own account is not a base-passwd name, which would leave its
    # entries to postinst; this test runs the script, so pin them here.
    monkeypatch.setattr("pkgforge.dbdump._debian._install_time", lambda o, g: False)

    user = pwd.getpwuid(os.getuid()).pw_name
    group = grp.getgrgid(os.getgid()).gr_name

    debian = tmp_path / "debian"
    tree = debian / "tool"
    tree.mkdir(parents=True)
    (tree / "x").mkdir()

    paths_modes = {
        "/a b": "751",
        "/it's": "600",
        "/x/d$HOME": "640",
        "/back\\slash": "751",
        "/star*": "600",
    }
    entries = []
    for path, mode in paths_modes.items():
        rel = path.lstrip("/")
        (tree / rel).write_text("x", encoding="utf-8")
        entries.append(
            (
                path,
                {
                    "mode": mode,
                    "owner": user,
                    "group": group,
                    "type": "file",
                    "kind": "file",
                    "caps": "-",
                    "package": "-",
                    "meta": {},
                },
            )
        )

    nonutf8_name = os.fsdecode(b"caf\xe9")
    (tree / nonutf8_name).write_bytes(b"x")
    entries.append(
        (
            "/" + nonutf8_name,
            {
                "mode": "640",
                "owner": user,
                "group": group,
                "type": "file",
                "kind": "file",
                "caps": "-",
                "package": "-",
                "meta": {},
            },
        )
    )

    # A symlink whose target lies outside the tree, with a known initial
    # mode: fixperms must never chmod it (chmod is skipped for a symlink
    # entry entirely) and must chown/chgrp -h (the link itself, not the
    # target) -- either slip would leave this target's mode changed.
    outside = tmp_path / "outside.txt"
    outside.write_text("x", encoding="utf-8")
    os.chmod(outside, 0o644)
    link = tree / "link"
    os.symlink(outside, link)
    entries.append(
        (
            "/link",
            {
                "mode": "600",
                "owner": user,
                "group": group,
                "type": "symlink",
                "kind": "file",
                "caps": "-",
                "package": "-",
                "meta": {},
            },
        )
    )

    arts = DebianFiles().render(entries, _CTX)
    script = tmp_path / "fixperms"
    script.write_bytes(arts["fixperms"])

    result = subprocess.run(
        ["sh", str(script), str(debian)], capture_output=True, text=True
    )
    assert result.returncode == 0, result.stderr

    for path, mode in paths_modes.items():
        got = stat.S_IMODE(os.stat(tree / path.lstrip("/")).st_mode)
        assert got == int(mode, 8), path

    got = stat.S_IMODE(os.stat(tree / nonutf8_name).st_mode)
    assert got == 0o640

    # The symlink's own target is untouched, both in mode and identity.
    assert stat.S_IMODE(os.stat(outside).st_mode) == 0o644
    assert os.path.realpath(link) == os.path.realpath(outside)


