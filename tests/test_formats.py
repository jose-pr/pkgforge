FIXPERMS_HEADER = (
    b"#!/bin/sh\n"
    b"# Generated by pkgforge dbdump -f debian. Usage: sh fixperms DEBIAN-DIR\n"
    b"set -e\n"
    b"d=${1:?usage: sh fixperms DEBIAN-DIR}\n"
    b"p() {\n"
    b'  for f in "$1" "$1.gz"; do\n'
    b'    if [ -e "$f" ] || [ -L "$f" ]; then printf \'%s\\n\' "$f"; return; fi\n'
    b"  done\n"
    b'  echo "fixperms: skipping missing $1" >&2\n'
    b"  return 1\n"
    b"}\n"
)


def line(path, cmds):
    """One pinned entry's line in the generated fixperms script."""
    word = shlex.quote("tool" + path)
    return f'if t=$(p "$d"/{word}); then {cmds}; fi\n'.encode(
        "utf-8", "surrogateescape"
    )


