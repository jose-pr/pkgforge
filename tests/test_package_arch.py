def _stage(cli) -> None:
    result = cli("stage", "--init")
    assert result.rc == 0, result.err


def _edit_cfg(work: Path, *pairs: typing.Tuple[str, str], append: str = "") -> None:
    path = work / "pkgforge.cfg"
    text = path.read_bytes().decode("utf-8")
    for old, new in pairs:
        assert text.count(old) == 1, old
        text = text.replace(old, new)
    path.write_bytes((text + append).encode("utf-8"))


@pytest.fixture
def staged(work, cli):
    _stage(cli)
    return work


def _package(cli, out: Path, *args: str):
    return cli("package", "-f", "arch", "-o", str(out), *args)


def _plain(name: str, data: bytes) -> bytes:
    if name.endswith(".gz"):
        return gzip.decompress(data)
    if name.endswith(".xz"):
        return lzma.decompress(data)
    assert name.endswith(".zst")
    try:
        from compression import zstd

        return zstd.decompress(data)
    except ImportError:
        import zstandard

        return zstandard.ZstdDecompressor().decompress(data)


class Package(typing.NamedTuple):
    raw: bytes
    members: typing.Dict[str, tarfile.TarInfo]
    data: typing.Dict[str, bytes]


def _read(path: Path) -> Package:
    raw = _plain(path.name, path.read_bytes())
    members, data = {}, {}
    with tarfile.open(fileobj=io.BytesIO(raw)) as archive:
        for member in archive.getmembers():
            members[member.name] = member
            if member.isreg():
                extracted = archive.extractfile(member)
                assert extracted is not None
                data[member.name] = extracted.read()
    return Package(raw, members, data)


def _info(package: Package) -> typing.List[typing.Tuple[str, str]]:
    lines = package.data[".PKGINFO"].decode("utf-8").splitlines()
    assert lines[0] == "# Generated by pkgforge"
    return [tuple(line.split(" = ", 1)) for line in lines[1:]]


@pytest.mark.posix
def test_arch_member_order_and_names(staged, cli, tmp_path):
    result = _package(cli, tmp_path / "out")
    assert result.rc == 0, result.err
    assert result.out.decode().splitlines() == [
        str(tmp_path / "out" / HELLO),
        str(tmp_path / "out" / DOC),
    ]
    hello = _read(tmp_path / "out" / HELLO)
    names = list(hello.members)
    assert names[:3] == [".PKGINFO", ".MTREE", ".INSTALL"]
    payload = names[3:]
    assert payload == sorted(payload)
    assert not any(
        name.startswith(("./", "/")) or name in (".", "./") for name in names
    )
    assert {"etc", "usr", "usr/bin", "var/lib/hello", "usr/bin/hi"} <= set(payload)
    assert not any(name.startswith("run") for name in payload)
    assert not any(name.endswith("hello.log") for name in payload)
    assert hello.raw[257:265] == b"ustar  \x00"
    assert hello.members["usr/bin/hi"].issym()
    assert hello.members["usr/bin/hi"].linkname == "hello"
    assert all(hello.members[name].mode == 0o644 for name in names[:3])

    doc = _read(tmp_path / "out" / DOC)
    assert list(doc.members)[:2] == [".PKGINFO", ".MTREE"]
    assert ".INSTALL" not in doc.members
    assert "usr/share/doc/hello-doc/README" in doc.members


@pytest.mark.posix
def test_arch_pkginfo(staged, cli, tmp_path, monkeypatch):
    monkeypatch.setenv("SOURCE_DATE_EPOCH", str(EPOCH))
    assert _package(cli, tmp_path / "out").rc == 0
    hello = _read(tmp_path / "out" / HELLO)
    sizes = sum(
        m.size for m in hello.members.values() if m.isreg() and m.name[0] != "."
    )
    sizes += len("hello")  # the usr/bin/hi target
    assert _info(hello) == [
        ("pkgname", "hello"),
        ("pkgbase", "hello"),
        ("xdata", "pkgtype=pkg"),
        ("pkgver", "1.0-1"),
        ("pkgdesc", "pkgforge example package"),
        ("builddate", str(EPOCH)),
        ("packager", "Example Maintainer <maintainer@example.org>"),
        ("size", str(sizes)),
        ("arch", "any"),
        ("license", "MIT"),
        ("depend", "systemd"),
        ("depend", "libcap"),
    ]
    assert hello.members[".PKGINFO"].mtime == EPOCH

    doc = _read(tmp_path / "out" / DOC)
    doc_sizes = sum(
        m.size for m in doc.members.values() if m.isreg() and m.name[0] != "."
    )
    assert _info(doc) == [
        ("pkgname", "hello-doc"),
        ("pkgbase", "hello"),
        ("xdata", "pkgtype=split"),
        ("pkgver", "1.0-1"),
        ("pkgdesc", "pkgforge example package documentation"),
        ("builddate", str(EPOCH)),
        ("packager", "Example Maintainer <maintainer@example.org>"),
        ("size", str(doc_sizes)),
        ("arch", "any"),
        ("license", "MIT"),
    ]


@pytest.mark.posix
def test_arch_pkginfo_url_packager_and_depends(work, cli, tmp_path):
    _edit_cfg(
        work,
        (
            'license = "MIT"\n',
            'license = "MIT"\nhomepage = "https://example.org/hello"\n',
        ),
        ('maintainer = "Example Maintainer <maintainer@example.org>"\n', ""),
        (
            'section = "misc"\n',
            'section = "misc"\n\n[package.pacman]\n'
            'depends = ["glibc", "bash>=5", "systemd"]\n',
        ),
        (
            'description = "The README of the pkgforge example package."\n',
            'description = "The README of the pkgforge example package."\n'
            '[packages.pacman]\ndepends = ["hello"]\n',
        ),
    )
    _stage(cli)
    assert _package(cli, tmp_path / "out").rc == 0
    hello = _info(_read(tmp_path / "out" / HELLO))
    keys = [key for key, _value in hello]
    assert keys.index("url") == keys.index("pkgdesc") + 1
    assert dict(hello)["url"] == "https://example.org/hello"
    assert dict(hello)["packager"] == "Unknown Packager"
    # Configured items first; systemd is listed once, then libcap.
    assert [value for key, value in hello if key == "depend"] == [
        "glibc",
        "bash>=5",
        "systemd",
        "libcap",
    ]
    doc = _info(_read(tmp_path / "out" / DOC))
    assert dict(doc)["url"] == "https://example.org/hello"
    assert [value for key, value in doc if key == "depend"] == ["hello"]


def _mtree(package: Package) -> typing.Dict[str, typing.Dict[str, str]]:
    lines = gzip.decompress(package.data[".MTREE"]).decode("ascii").splitlines()
    assert lines[0] == "#mtree"
    rows = {}
    for line in lines[1:]:
        name, *keys = line.split(" ")
        assert name.startswith("./")
        assert name not in rows
        rows[name] = dict(key.split("=", 1) for key in keys)
    return rows


def test_arch_mtree_escape():
    assert _arch._escape("plain/path-1.0") == "plain/path-1.0"
    assert _arch._escape("a b") == "a\\040b"
    assert _arch._escape("é") == "\\303\\251"
    assert _arch._escape("a#b\\c") == "a\\043b\\134c"
    assert _arch._escape("x*?[") == "x*?["
    assert _arch._escape("t\tn\n") == "t\\011n\\012"
    assert _arch._escape("\udcff") == "\\377"


@pytest.mark.posix
def test_arch_mtree_matches_payload(work, cli, tmp_path, monkeypatch):
    monkeypatch.setenv("SOURCE_DATE_EPOCH", str(EPOCH))
    _edit_cfg(
        work,
        append='\n[[stage]]\nsrc = "src/README"\ndest = "/opt/sp ace é"\nmode = "644"\n',
    )
    _stage(cli)
    assert _package(cli, tmp_path / "out").rc == 0
    for name in (HELLO, DOC):
        package = _read(tmp_path / "out" / name)
        rows = _mtree(package)
        wanted = {f"./{_arch._escape(member)}" for member in package.members}
        assert set(rows) == wanted - {"./.MTREE"}
        for member in package.members.values():
            if member.name == ".MTREE":
                continue
            row = rows[f"./{_arch._escape(member.name)}"]
            assert row["uid"] == row["gid"] == "0"
            assert row["mode"] == format(member.mode, "o")
            assert row["time"] == f"{member.mtime}.0"
            if member.isreg():
                content = package.data[member.name]
                assert row["type"] == "file" and row["size"] == str(len(content))
                assert row["md5digest"] == hashlib.md5(content).hexdigest()
                assert row["sha256digest"] == hashlib.sha256(content).hexdigest()
            elif member.issym():
                assert row["type"] == "link" and row["link"] == member.linkname
            else:
                assert row["type"] == "dir" and "size" not in row
    hello = _read(tmp_path / "out" / HELLO)
    assert "opt/sp ace é/README" in hello.members
    assert "./opt/sp\\040ace\\040\\303\\251/README" in _mtree(hello)
    # gzip header: no timestamp.
    assert hello.data[".MTREE"][4:8] == b"\0\0\0\0"


