@pytest.mark.posix
def test_arch_reproducible(staged, cli, tmp_path, monkeypatch):
    monkeypatch.setenv("SOURCE_DATE_EPOCH", str(EPOCH))
    assert _package(cli, tmp_path / "a").rc == 0
    assert _package(cli, tmp_path / "b").rc == 0
    for name in (HELLO, DOC):
        assert (tmp_path / "a" / name).read_bytes() == (
            tmp_path / "b" / name
        ).read_bytes()
    monkeypatch.setenv("SOURCE_DATE_EPOCH", str(EPOCH + 1))
    assert _package(cli, tmp_path / "c").rc == 0
    assert (tmp_path / "c" / HELLO).read_bytes() != (
        tmp_path / "a" / HELLO
    ).read_bytes()


@pytest.mark.posix
def test_arch_architecture_names(work, cli, tmp_path, monkeypatch):
    _stage(cli)
    assert _package(cli, tmp_path / "all", "--arch", "aarch64").rc == 0
    assert sorted(path.name for path in (tmp_path / "all").iterdir()) == [HELLO, DOC]

    _edit_cfg(work, ('arch = "all"\n', 'arch = "any"\n'))
    result = _package(cli, tmp_path / "any", "--arch", "armv7h")
