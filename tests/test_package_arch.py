@pytest.mark.posix
def test_arch_install_script_restores_setuid(work, cli, tmp_path):
    _edit_cfg(
        work,
        append=(
            '\n[[stage]]\nsrc = "src/helper"\ndest = "/usr/bin/suid tool"\n'
            'into = false\nmode = "4755"\nowner = "hello"\n'
        ),
    )
    _stage(cli)
    assert _package(cli, tmp_path / "out").rc == 0
    script = _read(tmp_path / "out" / HELLO).data[".INSTALL"].decode("utf-8")
    lines = script.splitlines()
    chown = lines.index("  chown -h -- hello:root '/usr/bin/suid tool'")
    assert lines[chown + 1] == "  chmod -- 4755 '/usr/bin/suid tool'"
    assert lines.index("  chown -h -- hello:hello /var/lib/hello") + 1 == lines.index(
        "  setcap cap_net_bind_service=ep /usr/libexec/hello/helper"
    )
    assert lines.index("  chown -h -- hello:hello /var/lib/hello") > chown


@pytest.mark.posix
def test_arch_install_script_owned_by_created_account(work, cli, tmp_path):
    """A package that owns a file by a created account makes it, though the
    sysusers file ships in another package."""
    _edit_cfg(
        work,
        (
            'src = "src/README"\ndest = "/usr/share/doc/hello-doc"\nmode = "644"\n',
            'src = "src/README"\ndest = "/usr/share/doc/hello-doc"\nmode = "644"\n'
            'owner = "hello"\n',
        ),
    )
    _stage(cli)
    assert _package(cli, tmp_path / "out").rc == 0
    doc = _read(tmp_path / "out" / DOC)
    script = doc.data[".INSTALL"].decode("utf-8")
    assert "systemd-sysusers - <<'PKGFORGE_SYSUSERS'" in script
    assert "systemd-tmpfiles" not in script
    assert "  chown -h -- hello:root /usr/share/doc/hello-doc/README\n" in script
    assert dict(_info(doc)).get("depend") == "systemd"


@pytest.mark.posix
def test_arch_headers_root(staged, cli, tmp_path):
    assert _package(cli, tmp_path / "out").rc == 0
    for name in (HELLO, DOC):
        package = _read(tmp_path / "out" / name)
        for member in package.members.values():
            assert (member.uid, member.gid) == (0, 0), member.name
            assert (member.uname, member.gname) == ("root", "root"), member.name
    # The recorded owners are still the modes the headers carry.
    hello = _read(tmp_path / "out" / HELLO)
    assert hello.members["etc/hello/hello.conf"].mode == 0o640
    assert hello.members["var/lib/hello"].mode == 0o750


