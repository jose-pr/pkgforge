    assert _package(cli, tmp_path / "host").rc == 0
    assert (tmp_path / "host/hello-1.0-1-aarch64.pkg.tar.zst").exists()

    monkeypatch.setattr("platform.machine", lambda: "ppc64le")
    result = _package(cli, tmp_path / "bad")
    assert result.rc == 2
    assert b"no architecture name for machine 'ppc64le': pass --arch" in result.err


