def _cli_project(tmp_path, make_entry, *, cfg_name="pkgforge.cfg"):
    cfg = tmp_path / cfg_name
    cfg.write_text(
        '[package]\nname = "tool"\nversion = "1.0"\nsummary = "A tool"\n'
        f'license = "MIT"\nmaintainer = "{MAINTAINER}"\n',
        encoding="utf-8",
    )
    db = tmp_path / "files.jsonl"
    db.write_text(jsonl_line("/usr/bin/tool", make_entry(mode="755")), encoding="utf-8")
    return cfg, db


