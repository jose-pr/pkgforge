# -- debian --skeleton ------------------------------------------------------


def _skeleton(tmp_path, make_entry, config=None, *, cfg=None, **kwargs):
    cfg = tmp_path / "pkgforge.cfg" if cfg is None else cfg
    out = tmp_path / "debian"
    dump(
        _entries(make_entry),
        "debian",
        out,
        config=config or _config(),
        config_path=cfg,
        skeleton=True,
        **kwargs,
    )
    return out


