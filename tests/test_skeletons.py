def _cfg_argument(rules: Path) -> str:
    lines = [
        line
        for line in rules.read_text(encoding="utf-8").splitlines()
        if "stage --init" in line
    ]
    assert len(lines) == 1
    return lines[0].split("--config ", 1)[1].rsplit(" stage", 1)[0]


