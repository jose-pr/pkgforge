def _config(**over):
    data = {
        "package": {
            "name": "tool",
            "version": "1.0",
            "release": "2",
            "summary": "A tool",
            "license": "MIT",
            "maintainer": MAINTAINER,
            "homepage": "https://example.org/tool",
            "description": "Line one.\n\nLine 100% two.",
            "arch": "all",
            "rpm": {"requires": ["bash"]},
            "debian": {"section": "utils", "depends": ["bash"]},
        },
        "packages": [
            {"name": "tool-doc", "summary": "Docs", "description": "The docs."}
        ],
    }
    data.update(over)
    return ProjectConfig.from_dict(data)


def _entries(make_entry, *extra):
    db = {
        "/usr/bin/tool": make_entry(mode="755"),
        "/usr/share/doc/tool-doc/README": make_entry(package="tool-doc", kind="doc"),
    }
    db.update(dict(extra))
    return db


def _spec(db, config, fmt="rpmspec"):
    return dump(db, fmt, None, config=config).decode("utf-8")


