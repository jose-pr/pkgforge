def test_spec_preamble_and_install(make_entry):
    spec = _spec(_entries(make_entry), _config())
    assert spec.startswith("# Generated by pkgforge dbdump -f rpmspec")
    assert "%{!?pkgforge_config:%{error:define pkgforge_config" in spec
    assert "%global __os_install_post %{nil}\n%global debug_package %{nil}\n" in spec
    for line in (
        "Name:           tool",
        "Version:        1.0",
        "Release:        2",
        "Summary:        A tool",
        "License:        MIT",
        "URL:            https://example.org/tool",
        "BuildArch:      noarch",
        "Requires:       bash",
    ):
        assert f"\n{line}\n" in spec
    assert "\n%description\nLine one.\n\nLine 100%% two.\n" in spec
    assert (
        "\n%install\n"
        "export PKGFORGE_ROOT=%{buildroot} PKGFORGE_DB=%{_builddir}/pkgforge.jsonl\n"
        'pkgforge -q --config "%{pkgforge_config}" stage --init\n'
        "mkdir -p %{_builddir}/pkgforge-files\n"
        'pkgforge -q --config "%{pkgforge_config}" dbdump -f rpmspecfiles '
        "%{_builddir}/pkgforge-files\n"
    ) in spec
    assert "%{proj}" not in spec


