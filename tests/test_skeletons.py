def test_cli_force_replaces_the_spec(tmp_path, make_entry, cli, caplog):
    cfg, db = _cli_project(tmp_path, make_entry)
    spec = tmp_path / "tool.spec"
    spec.write_text("mine\n", encoding="utf-8")
    base = ("--config", str(cfg), "--db", str(db), "dbdump", "-f", "rpmspec")
    with caplog.at_level(logging.WARNING, logger="pkgforge.dbdump"):
        kept = cli(*base, str(spec))
    assert kept.rc == 0
    assert spec.read_text(encoding="utf-8") == "mine\n"
    assert f"kept existing {spec} (pass --force to replace it)" in caplog.messages
    forced = cli(*base, "--force", str(spec))
    assert forced.rc == 0
    assert spec.read_text(encoding="utf-8").startswith("# Generated by pkgforge")


