def _accounts(make_entry, package="-"):
    return _entries(
        make_entry,
        ("/usr/lib/sysusers.d/tool.conf", make_entry(package=package)),
        ("/usr/lib/tmpfiles.d/tool.conf", make_entry(package=package)),
    )


def test_spec_pre_scriptlet_only_for_rpm_below_419(make_entry):
    config = _config(users=[{"name": "tool", "description": "tool 100%"}])
    db = _accounts(make_entry)
    spec = _spec(db, config)
    assert "%pre" not in spec
    pre = _spec(db, config, "rpmspec-pre419")
    assert "dbdump -f rpmspecfiles-pre419 " in pre
    assert (
        "\n%pre\nsystemd-sysusers - <<'PKGFORGE_SYSUSERS' || :\n"
        "# Generated by pkgforge from pkgforge.cfg; do not edit.\n"
    ) in pre
    # Doubled once for sysusers.d, once for the spec.
    assert 'u tool - "tool 100%%%%" ' in pre
    assert "\nPKGFORGE_SYSUSERS\n" in pre


