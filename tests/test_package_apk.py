"""``pkgforge package -f apk``: the two gzip members, ``.PKGINFO``, the
checksums and the scripts, read back by pure-Python readers."""

from __future__ import annotations

import hashlib
import io
import os
import shutil
import tarfile
import typing
import zlib
from pathlib import Path

import pytest

from conftest import skip_if_fs_rejects_non_utf8

EXAMPLES = Path(__file__).resolve().parents[1] / "examples"
EPOCH = 1_500_000_000
HELLO = "hello-1.0-r1.apk"
DOC = "hello-doc-1.0-r1.apk"


