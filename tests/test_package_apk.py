def _stage(cli) -> None:
    result = cli("stage", "--init")
    assert result.rc == 0, result.err


def _edit_cfg(work: Path, *pairs: typing.Tuple[str, str], append: str = "") -> None:
    path = work / "pkgforge.cfg"
    text = path.read_bytes().decode("utf-8")
    for old, new in pairs:
        assert text.count(old) == 1, old
        text = text.replace(old, new)
    path.write_bytes((text + append).encode("utf-8"))


@pytest.fixture
def staged(work, cli):
    _stage(cli)
    return work


def _package(cli, out: Path, *args: str):
    return cli("package", "-f", "apk", "-o", str(out), *args)


def _members(data: bytes) -> typing.List[bytes]:
    """The gzip members of ``data``, decompressed, in order."""
    out = []
    while data:
        stream = zlib.decompressobj(31)
        out.append(stream.decompress(data))
        assert stream.eof
        data = stream.unused_data
    return out


class Package(typing.NamedTuple):
    control_raw: bytes
    data_raw: bytes
    control: typing.Dict[str, tarfile.TarInfo]
    control_data: typing.Dict[str, bytes]
    members: typing.Dict[str, tarfile.TarInfo]
    data: typing.Dict[str, bytes]
    #: The second gzip member as stored.
    data_gz: bytes


def _tar(raw: bytes) -> typing.Tuple[typing.Dict, typing.Dict]:
    members, data = {}, {}
    with tarfile.open(fileobj=io.BytesIO(raw)) as archive:
        for member in archive.getmembers():
            members[member.name] = member
            if member.isreg():
                extracted = archive.extractfile(member)
                assert extracted is not None
                data[member.name] = extracted.read()
    return members, data


def _read(path: Path) -> Package:
    stored = path.read_bytes()
    control_raw, data_raw = _members(stored)
    control, control_data = _tar(control_raw)
    members, data = _tar(data_raw)
    first = zlib.decompressobj(31)
    first.decompress(stored)
    return Package(
        control_raw,
        data_raw,
        control,
        control_data,
        members,
        data,
        first.unused_data,
    )


def _info(package: Package) -> typing.List[typing.Tuple[str, str]]:
    lines = package.control_data[".PKGINFO"].decode("utf-8").splitlines()
    assert lines[0] == "# Generated by pkgforge"
    return [tuple(line.split(" = ", 1)) for line in lines[1:]]


@pytest.mark.posix
def test_apk_two_gzip_members(staged, cli, tmp_path):
    result = _package(cli, tmp_path / "out")
    assert result.rc == 0, result.err
    assert result.out.decode().splitlines() == [
        str(tmp_path / "out" / HELLO),
        str(tmp_path / "out" / DOC),
    ]
    hello = _read(tmp_path / "out" / HELLO)
    assert list(hello.control) == [
        ".PKGINFO",
        ".pre-install",
        ".pre-upgrade",
        ".post-install",
        ".post-upgrade",
    ]
    assert hello.control[".PKGINFO"].mode == 0o644
    assert {hello.control[name].mode for name in list(hello.control)[1:]} == {0o755}
    # The data member is a pax archive: POSIX magic, and extended headers.
    assert hello.data_raw[257:265] == b"ustar\x0000"
    assert b"APK-TOOLS.checksum.SHA1=" in hello.data_raw
    assert hello.data_raw.endswith(b"\0" * 1024)
    names = list(hello.members)
    assert not any(name.startswith(("./", "/")) for name in names)
    assert {"etc", "usr", "usr/bin", "var/lib/hello", "usr/bin/hi"} <= set(names)
    assert not any(name.startswith("run") for name in names)
    assert hello.members["usr/bin/hi"].issym()
    assert hello.members["usr/bin/hi"].linkname == "hello"

    doc = _read(tmp_path / "out" / DOC)
    assert list(doc.control) == [".PKGINFO"]
    assert "usr/share/doc/hello-doc/README" in doc.members


@pytest.mark.posix
def test_apk_control_has_no_end_blocks(staged, cli, tmp_path):
    assert _package(cli, tmp_path / "out").rc == 0
    for name in (HELLO, DOC):
        package = _read(tmp_path / "out" / name)
        blocks = sum(1 + -(-member.size // 512) for member in package.control.values())
        assert len(package.control_raw) == 512 * blocks
        assert not package.control_raw.endswith(b"\0" * 1024)


@pytest.mark.posix
def test_apk_pkginfo(staged, cli, tmp_path, monkeypatch):
    monkeypatch.setenv("SOURCE_DATE_EPOCH", str(EPOCH))
    assert _package(cli, tmp_path / "out").rc == 0
    hello = _read(tmp_path / "out" / HELLO)
    size = sum(m.size for m in hello.members.values() if m.isreg())
    size += len("hello")  # the usr/bin/hi target
    assert _info(hello) == [
        ("pkgname", "hello"),
        ("pkgver", "1.0-r1"),
        ("pkgdesc", "pkgforge example package"),
        ("builddate", str(EPOCH)),
        ("packager", "Example Maintainer <maintainer@example.org>"),
        ("size", str(size)),
        ("arch", "noarch"),
        ("origin", "hello"),
        ("maintainer", "Example Maintainer <maintainer@example.org>"),
        ("license", "MIT"),
        ("depend", "libcap-setcap"),
        ("datahash", hashlib.sha256(hello.data_gz).hexdigest()),
    ]
    assert hello.control[".PKGINFO"].mtime == EPOCH

    doc = _read(tmp_path / "out" / DOC)
    doc_size = sum(m.size for m in doc.members.values() if m.isreg())
    assert _info(doc) == [
        ("pkgname", "hello-doc"),
        ("pkgver", "1.0-r1"),
        ("pkgdesc", "pkgforge example package documentation"),
        ("builddate", str(EPOCH)),
        ("packager", "Example Maintainer <maintainer@example.org>"),
        ("size", str(doc_size)),
        ("arch", "noarch"),
        ("origin", "hello"),
        ("maintainer", "Example Maintainer <maintainer@example.org>"),
        ("license", "MIT"),
        ("datahash", hashlib.sha256(doc.data_gz).hexdigest()),
    ]


@pytest.mark.posix
def test_apk_pkginfo_optional_keys_and_depends(work, cli, tmp_path):
    _edit_cfg(
        work,
        (
            'license = "MIT"\n',
            'license = "MIT"\nhomepage = "https://example.org/hello"\n',
        ),
        ('maintainer = "Example Maintainer <maintainer@example.org>"\n', ""),
        ('release = "1"\n', ""),
        (
            'section = "misc"\n',
            'section = "misc"\n\n[package.apk]\ndepends = ["musl", "bash>=5"]\n',
        ),
        (
            'description = "The README of the pkgforge example package."\n',
            'description = "The README of the pkgforge example package."\n'
            '[packages.apk]\ndepends = ["hello"]\n',
        ),
    )
    _stage(cli)
    assert _package(cli, tmp_path / "out").rc == 0
    hello = _info(_read(tmp_path / "out" / "hello-1.0-r0.apk"))
    keys = [key for key, _value in hello]
    assert keys.index("url") == keys.index("pkgdesc") + 1
    assert dict(hello)["url"] == "https://example.org/hello"
    assert dict(hello)["packager"] == "Unknown"
    assert "maintainer" not in keys
    assert [value for key, value in hello if key == "depend"] == [
        "musl",
        "bash>=5",
        "libcap-setcap",
    ]
    doc = _info(_read(tmp_path / "out" / "hello-doc-1.0-r0.apk"))
    assert [value for key, value in doc if key == "depend"] == ["hello"]


@pytest.mark.posix
def test_apk_checksums(staged, cli, tmp_path):
    assert _package(cli, tmp_path / "out").rc == 0
    for name in (HELLO, DOC):
        package = _read(tmp_path / "out" / name)
        seen = 0
        for member in package.members.values():
            record = member.pax_headers.get("APK-TOOLS.checksum.SHA1")
            if member.isreg():
                assert record == hashlib.sha1(package.data[member.name]).hexdigest()
            elif member.issym():
                assert record == hashlib.sha1(member.linkname.encode()).hexdigest()
            else:
                assert record is None, member.name
                continue
            seen += 1
        assert seen
    hello = _read(tmp_path / "out" / HELLO)
    assert hello.members["usr/bin/hi"].pax_headers["APK-TOOLS.checksum.SHA1"]


@pytest.mark.posix
def test_apk_owner_names(staged, cli, tmp_path):
    assert _package(cli, tmp_path / "out").rc == 0
    hello = _read(tmp_path / "out" / HELLO)
    state = hello.members["var/lib/hello"]
    assert (state.uname, state.gname, state.mode) == ("hello", "hello", 0o750)
    conf = hello.members["etc/hello/hello.conf"]
    assert (conf.uname, conf.gname, conf.mode) == ("root", "adm", 0o640)
    for member in hello.members.values():
        assert (member.uid, member.gid) == (0, 0), member.name
    assert hello.members["usr/bin"].uname == "root"


@pytest.mark.posix
def test_apk_scripts(staged, cli, tmp_path):
    assert _package(cli, tmp_path / "out").rc == 0
    hello = _read(tmp_path / "out" / HELLO)
    pre = (
        "#!/bin/sh\n"
        "addgroup -S hello 2>/dev/null || :\n"
        "adduser -S -D -H -h /var/lib/hello -s /sbin/nologin -G hello "
        "-g 'hello example daemon' hello 2>/dev/null || :\n"
        "exit 0\n"
    )
    post = (
        "#!/bin/sh\n"
        "mkdir -p -- /run/hello && chown -- hello:hello /run/hello "
        "&& chmod -- 0755 /run/hello\n"
        "setcap cap_net_bind_service=ep /usr/libexec/hello/helper\n"
        "exit 0\n"
    )
    for name in (".pre-install", ".pre-upgrade"):
        assert hello.control_data[name].decode("utf-8") == pre
    for name in (".post-install", ".post-upgrade"):
        assert hello.control_data[name].decode("utf-8") == post
    doc = _read(tmp_path / "out" / DOC)
    assert not [name for name in doc.control if name.startswith(".p")]


