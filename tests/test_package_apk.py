@pytest.mark.posix
def test_apk_non_utf8_path_exit_1(work, cli, tmp_path):
    _stage(cli)
    root = tmp_path / "root"
    skip_if_fs_rejects_non_utf8(root)
    bad = root / "opt" / os.fsdecode(b"bad-\xff")
    bad.parent.mkdir()
    bad.write_bytes(b"x")
    assert cli("scan", "/opt").rc == 0
    result = _package(cli, tmp_path / "out")
    assert result.rc == 1
    assert b"apk needs UTF-8 paths" in result.err
    assert not list((tmp_path / "out").glob("*.apk"))


@pytest.mark.posix
def test_apk_reproducible(staged, cli, tmp_path, monkeypatch):
    monkeypatch.setenv("SOURCE_DATE_EPOCH", str(EPOCH))
    assert _package(cli, tmp_path / "a").rc == 0
    assert _package(cli, tmp_path / "b").rc == 0
    for name in (HELLO, DOC):
        assert (tmp_path / "a" / name).read_bytes() == (
            tmp_path / "b" / name
        ).read_bytes()
    monkeypatch.setenv("SOURCE_DATE_EPOCH", str(EPOCH + 1))
    assert _package(cli, tmp_path / "c").rc == 0
    assert (tmp_path / "c" / HELLO).read_bytes() != (
        tmp_path / "a" / HELLO
    ).read_bytes()


